#    检查文件名结构是否正确，并且 p[4] (episode编号) 是否在数字上大于 1000。
#    AWK 会自动将 "001001" 转换成数字 1001 进行比较。
# 4. print $0 : 如果条件满足，打印完整的文件路径 ( $0 )。
# -----------------
