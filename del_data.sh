BEGIN { FS = "/" }
{
    filename = $NF
    split(filename, p, "_")
    
    # 检查文件名结构是否符合预期，并且 episode 编号是否 > 1000
    if (p[1] == "env" && p[3] == "episode" && p[4] > 1000) {
        print $0  # 打印完整路径
