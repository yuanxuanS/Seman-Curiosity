# AWK 脚本逻辑：
# 1. -F/ : 将字段分隔符设置为'/'，这样 $NF (最后一个字段) 就是文件名。
# 2. split($NF, p, "_") : 将文件名 (如 "env_00_episode_001001_...") 按"_"分割存入数组 p。
#    p[1]="env", p[2]="00", p[3]="episode", p[4]="001001", ...
